-- ============================================================================
--  Plano de venta de lotes - tablas.
--  Cada area de MAP_AREA con categoria 'Lote' tiene una fila en MAP_LOTE con los datos
--  de venta; calles, plaza y perimetro quedan como contexto del plano.
--  Precio por plazo: cada plan (contado, 12, 36, 60, 120 cuotas...) tiene un recargo %
--  sobre el precio contado; un lote puntual puede tener precio especial (MAP_LOTE_PRECIO).
--  Idempotente (atrapa "ya existe").
-- ============================================================================
declare
  n number;
  procedure ddl(p varchar2) is
  begin execute immediate p;
  exception when others then if sqlcode not in (-955,-1430,-2260,-2261,-2264,-1442,-1451,-1408) then raise; end if; end;
begin
  -- Datos del loteamiento (una sola fila, LOO_CODIGO = 1)
  ddl(q'~create table MAP_LOTEO (
    LOO_CODIGO      number        default 1 not null,
    LOO_NOMBRE      varchar2(150) not null,
    LOO_LEMA        varchar2(250),
    LOO_DESCRIPCION varchar2(2000),
    LOO_UBICACION   varchar2(250),                    -- texto: "Luque, Central"
    LOO_WHATSAPP    varchar2(20),                     -- 595...
    LOO_MAPS        varchar2(500),                    -- link de Google Maps de la entrada
    LOO_MOSTRAR_VENDIDOS varchar2(1) default 'S' not null,
    LOO_FECHA_MOD   date,
    LOO_USUARIO_MOD varchar2(100),
    constraint MAP_LOTEO_PK  primary key (LOO_CODIGO),
    constraint MAP_LOTEO_UNO check (LOO_CODIGO = 1),
    constraint MAP_LOTEO_VEN_CHK check (LOO_MOSTRAR_VENDIDOS in ('S','N'))
  )~');
  -- retiros (m) para "Que puedo construir?" y radio de busqueda del entorno
  ddl(q'~alter table MAP_LOTEO add (LOO_RETIRO_FRENTE  number(5,2) default 3    not null)~');
  ddl(q'~alter table MAP_LOTEO add (LOO_RETIRO_LATERAL number(5,2) default 1.5  not null)~');
  ddl(q'~alter table MAP_LOTEO add (LOO_RETIRO_FONDO   number(5,2) default 3    not null)~');
  ddl(q'~alter table MAP_LOTEO add (LOO_POI_RADIO      number(6)   default 3000 not null)~');
  ddl(q'~alter table MAP_LOTEO add (LOO_POI_FECHA      date)~');
  -- horarios de visita (1=lunes ... 7=domingo) y horas de la pre-reserva
  ddl(q'~alter table MAP_LOTEO add (LOO_VISITA_DIAS  varchar2(20)  default '1,2,3,4,5,6' not null)~');
  ddl(q'~alter table MAP_LOTEO add (LOO_VISITA_HORAS varchar2(200) default '08:00,09:00,10:00,11:00,14:00,15:00,16:00,17:00' not null)~');
  ddl(q'~alter table MAP_LOTEO add (LOO_RESERVA_HS   number(3)     default 48 not null)~');

  ddl(q'~create table MAP_LOTEO_PLAN (
    PLA_CODIGO      number generated by default as identity,
    PLA_CUOTAS      number(3)    not null,            -- 0 = contado
    PLA_RECARGO_PCT number(6,2)  default 0 not null,  -- sobre el precio contado
    PLA_ENTREGA_PCT number(5,2)  default 0 not null,  -- entrega minima, % del precio del plan
    PLA_ACTIVO      varchar2(1)  default 'S' not null,
    constraint MAP_LOTEO_PLAN_PK  primary key (PLA_CODIGO),
    constraint MAP_LOTEO_PLAN_UK  unique (PLA_CUOTAS),
    constraint MAP_LOTEO_PLAN_CHK check (PLA_CUOTAS between 0 and 240 and PLA_RECARGO_PCT between 0 and 500
                                         and PLA_ENTREGA_PCT between 0 and 100 and PLA_ACTIVO in ('S','N'))
  )~');

  ddl(q'~create table MAP_LOTE (
    LOT_ARE_CODIGO  number        not null,           -- = MAP_AREA.ARE_CODIGO (1 a 1)
    LOT_MANZANA     varchar2(10)  not null,
    LOT_NUMERO      varchar2(10)  not null,
    LOT_ESTADO      varchar2(10)  default 'DISPONIBLE' not null,
    LOT_PRECIO      number(14),                       -- contado
    LOT_FRENTE_M    number(7,2),
    LOT_FONDO_M     number(7,2),
    LOT_ESQUINA     varchar2(1)   default 'N' not null,
    LOT_PUBLICO     varchar2(1)   default 'S' not null,
    LOT_DETALLE     varchar2(500),                    -- lo ve el cliente: "frente a la plaza"
    LOT_NOTA        varchar2(1000),                   -- interna: nunca sale en la pagina publica
    LOT_FECHA_MOD   date,
    LOT_USUARIO_MOD varchar2(100),
    constraint MAP_LOTE_PK     primary key (LOT_ARE_CODIGO),
    constraint MAP_LOTE_ARE_FK foreign key (LOT_ARE_CODIGO) references MAP_AREA (ARE_CODIGO) on delete cascade,
    constraint MAP_LOTE_UK     unique (LOT_MANZANA, LOT_NUMERO),
    constraint MAP_LOTE_EST_CHK check (LOT_ESTADO in ('DISPONIBLE','RESERVADO','VENDIDO')),
    constraint MAP_LOTE_FLG_CHK check (LOT_ESQUINA in ('S','N') and LOT_PUBLICO in ('S','N')),
    constraint MAP_LOTE_NUM_CHK check (nvl(LOT_PRECIO, 0) >= 0 and nvl(LOT_FRENTE_M, 1) > 0 and nvl(LOT_FONDO_M, 1) > 0)
  )~');

  ddl(q'~create table MAP_LOTE_PRECIO (
    LPR_ARE_CODIGO  number     not null,
    LPR_CUOTAS      number(3)  not null,
    LPR_TOTAL       number(14) not null,              -- precio total especial para ese plan
    constraint MAP_LOTE_PRECIO_PK     primary key (LPR_ARE_CODIGO, LPR_CUOTAS),
    constraint MAP_LOTE_PRECIO_LOT_FK foreign key (LPR_ARE_CODIGO) references MAP_LOTE (LOT_ARE_CODIGO) on delete cascade,
    constraint MAP_LOTE_PRECIO_CHK    check (LPR_TOTAL > 0)
  )~');

  -- Puntos de interes cercanos (escuelas, salud...). Se cargan desde la gestion (OpenStreetMap).
  ddl(q'~create table MAP_LOTEO_POI (
    POI_CODIGO     number generated by default as identity,
    POI_CATEGORIA  varchar2(20)  not null,   -- ESCUELA | SALUD | SUPER | COMBUSTIBLE | BANCO | RUTA | OTRO
    POI_NOMBRE     varchar2(200) not null,
    POI_LAT        number(10,7)  not null,
    POI_LNG        number(10,7)  not null,
    POI_DIST_M     number(8),                -- distancia en linea recta al loteamiento
    POI_OSM_ID     varchar2(40),
    POI_ACTIVO     varchar2(1) default 'S' not null,
    constraint MAP_LOTEO_POI_PK  primary key (POI_CODIGO),
    constraint MAP_LOTEO_POI_CAT check (POI_CATEGORIA in ('ESCUELA','SALUD','SUPER','COMBUSTIBLE','BANCO','RUTA','OTRO')),
    constraint MAP_LOTEO_POI_ACT check (POI_ACTIVO in ('S','N'))
  )~');

  -- Historial de estados: "vendido hace N dias" y "asi se fue vendiendo".
  ddl(q'~create table MAP_LOTE_HIST (
    HIS_CODIGO     number generated by default as identity,
    HIS_ARE_CODIGO number       not null,
    HIS_ESTADO     varchar2(10) not null,
    HIS_FECHA      date         not null,
    HIS_USUARIO    varchar2(100),
    constraint MAP_LOTE_HIST_PK     primary key (HIS_CODIGO),
    constraint MAP_LOTE_HIST_LOT_FK foreign key (HIS_ARE_CODIGO) references MAP_LOTE (LOT_ARE_CODIGO) on delete cascade,
    constraint MAP_LOTE_HIST_EST    check (HIS_ESTADO in ('DISPONIBLE','RESERVADO','VENDIDO'))
  )~');
  ddl(q'~create index MAP_LOTE_HIST_IX on MAP_LOTE_HIST (HIS_ARE_CODIGO, HIS_FECHA)~');

  -- Lo que pide el cliente desde la pagina publica:
  --   VISITA (fecha y hora), AVISO ("avisame si se libera"), RESERVA (pre-reserva por LOO_RESERVA_HS horas)
  ddl(q'~create table MAP_LOTE_SOLICITUD (
    SOL_CODIGO     number generated by default as identity,
    SOL_ARE_CODIGO number,                              -- null en una visita general
    SOL_TIPO       varchar2(10)  not null,
    SOL_NOMBRE     varchar2(120) not null,
    SOL_TELEFONO   varchar2(20)  not null,              -- 595...
    SOL_VISITA     date,
    SOL_NOTA       varchar2(500),
    SOL_ESTADO     varchar2(12)  default 'PENDIENTE' not null,
    SOL_VENCE      date,
    SOL_CREADO     date          not null,
    SOL_ATENDIDO   date,
    SOL_USUARIO    varchar2(100),
    constraint MAP_LOTE_SOL_PK     primary key (SOL_CODIGO),
    constraint MAP_LOTE_SOL_LOT_FK foreign key (SOL_ARE_CODIGO) references MAP_LOTE (LOT_ARE_CODIGO) on delete cascade,
    constraint MAP_LOTE_SOL_TIP    check (SOL_TIPO in ('VISITA','AVISO','RESERVA')),
    constraint MAP_LOTE_SOL_EST    check (SOL_ESTADO in ('PENDIENTE','CONFIRMADA','ATENDIDA','DESCARTADA','VENCIDA'))
  )~');
  ddl(q'~create index MAP_LOTE_SOL_IX  on MAP_LOTE_SOLICITUD (SOL_ARE_CODIGO, SOL_TIPO, SOL_ESTADO)~');
  ddl(q'~create index MAP_LOTE_SOL_VIS on MAP_LOTE_SOLICITUD (SOL_VISITA)~');
  ddl(q'~create index MAP_LOTE_SOL_TEL on MAP_LOTE_SOLICITUD (SOL_TELEFONO, SOL_CREADO)~');

  -- Avance de obras del loteamiento (calles, energia, agua...). Foto opcional.
  ddl(q'~create table MAP_LOTEO_OBRA (
    OBR_CODIGO      number generated by default as identity,
    OBR_TITULO      varchar2(120) not null,
    OBR_DESCRIPCION varchar2(500),
    OBR_ESTADO      varchar2(10)  default 'PENDIENTE' not null,
    OBR_FECHA       date,                               -- terminada o prevista
    OBR_ORDEN       number        default 10 not null,
    OBR_FOTO        blob,
    OBR_FOTO_MIME   varchar2(60),
    constraint MAP_LOTEO_OBRA_PK  primary key (OBR_CODIGO),
    constraint MAP_LOTEO_OBRA_EST check (OBR_ESTADO in ('HECHO','EN_CURSO','PENDIENTE'))
  )~');

  -- Vista previa al compartir (Open Graph): una imagen por lote (OG_CLAVE = ARE_CODIGO) y una general (0).
  ddl(q'~create table MAP_LOTE_OG (
    OG_CLAVE  number       not null,
    OG_IMG    blob         not null,
    OG_MIME   varchar2(30) not null,
    OG_FECHA  date         not null,
    constraint MAP_LOTE_OG_PK primary key (OG_CLAVE)
  )~');

  -- Datos iniciales: el loteamiento y los planes de pago (solo si no existen)
  execute immediate 'select count(*) from MAP_LOTEO' into n;
  if n = 0 then
    execute immediate q'~insert into MAP_LOTEO (LOO_CODIGO, LOO_NOMBRE) values (1, 'Mi loteamiento')~';
  end if;
  execute immediate 'select count(*) from MAP_LOTEO_PLAN' into n;
  if n = 0 then
    execute immediate 'insert into MAP_LOTEO_PLAN (PLA_CUOTAS, PLA_RECARGO_PCT, PLA_ENTREGA_PCT) values (0,   0,  100)';
    execute immediate 'insert into MAP_LOTEO_PLAN (PLA_CUOTAS, PLA_RECARGO_PCT, PLA_ENTREGA_PCT) values (12,  10, 20)';
    execute immediate 'insert into MAP_LOTEO_PLAN (PLA_CUOTAS, PLA_RECARGO_PCT, PLA_ENTREGA_PCT) values (36,  25, 10)';
    execute immediate 'insert into MAP_LOTEO_PLAN (PLA_CUOTAS, PLA_RECARGO_PCT, PLA_ENTREGA_PCT) values (60,  40, 10)';
    execute immediate 'insert into MAP_LOTEO_PLAN (PLA_CUOTAS, PLA_RECARGO_PCT, PLA_ENTREGA_PCT) values (120, 70, 5)';
  end if;
  commit;
end;

--  Los lotes son poligonos de la tabla MAP_AREA (GeoJSON). Es la misma tabla del
--  modulo "Croquis y areas" del kit https://github.com/Fernand-v/apex-mapas-leaflet
--  (sql/40_areas_tablas.sql): si ya lo instalaste, este archivo no cambia nada y
